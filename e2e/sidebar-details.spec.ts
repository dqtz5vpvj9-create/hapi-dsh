/** Unchanged official DSH UI with explicit HAPI catalog fixtures; no model calls. */
import { test, expect, type Page } from '@playwright/test'
import { startOfficialEnvironment, type OfficialEnvironment } from './official-runtime.ts'

async function admit(page: Page, environment: OfficialEnvironment): Promise<void> {
    await page.goto(environment.launchUrl)
    await expect(page.locator('[data-hapi-workspace]')).toBeVisible()
    const notice = page.getByRole('dialog', { name: 'Preview Notice', exact: true })
    await expect(notice).toBeVisible()
    await notice.getByRole('button', { name: 'Continue', exact: true }).click()
}
const dayValue = (day: number): string => {
    const now = new Date()
    return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(day).padStart(2, '0')}`
}

test.describe('original HAPI compact search, calendar and row detail semantics', () => {
    let environment: OfficialEnvironment
    test.beforeEach(async () => { environment = await startOfficialEnvironment() })
    test.afterEach(async () => { await environment?.close() })

    test('weighted source metadata search, compact clear focus, backwards calendar range and true worktree base creation', async ({ page }, info) => {
        const errors: string[] = []
        page.on('pageerror', error => errors.push(error.message))
        const add = (key: string, title: string, path: string, day: number) => {
            const value = environment.hapi.add(key, 'Laptop', 'machine-alpha')
            value.session.metadata!.name = title; value.session.metadata!.path = path
            const now = new Date(); now.setDate(day); now.setHours(12, 0, 0, 0)
            value.session.updatedAt = now.getTime()
            environment.hapi.emit({ type: 'session-added', sessionId: value.session.id })
            return value
        }
        add('search-exact', 'Home Assistant', '/workspace/exact', 10)
        add('search-helper', 'Home Assistant helper', '/workspace/helper', 12)
        add('search-path', 'Incidental title', '/workspace/home-assistant', 15)
        const tree = add('search-tree', 'Feature plan', '/workspace/home.worktrees/feature-ui', 20)
        tree.session.metadata!.summary = { text: 'Ledger settlement work' }
        Object.assign(tree.session.metadata!, { codexAgentNickname: 'reviewer', worktree: { name: 'feature-ui', basePath: '/workspace/home', branch: 'feat/ui' } })
        environment.hapi.emit({ type: 'session-updated', sessionId: tree.session.id })
        await admit(page, environment)
        const sidebar = page.locator('.hapi-session-sidebar'), list = sidebar.locator('.hapi-session-list')
        await expect(list.locator('[data-recent-total]')).toHaveAttribute('data-recent-total', '6')
        await expect(sidebar.getByRole('searchbox')).toHaveCount(0)
        await sidebar.getByRole('button', { name: 'Search conversations', exact: true }).click()
        const search = sidebar.getByRole('searchbox')
        await expect(search).toBeFocused()
        await search.fill('Home Assistant')
        await expect(list.locator('[data-recent-total]')).toHaveAttribute('data-recent-total', '3')
        await expect(list.locator('.hapi-session-open').first()).toContainText('Home Assistant')
        await expect(list.locator('.hapi-session-open').first()).not.toContainText('helper')
        await search.fill('ledger reviewer laptop')
        await expect(list.locator('[data-recent-total]')).toHaveAttribute('data-recent-total', '1')
        await expect(list.locator('.hapi-session-open')).toContainText('Feature plan')
        await search.fill('*/home.worktrees/*')
        await expect(list.locator('[data-recent-total]')).toHaveAttribute('data-recent-total', '1')
        await sidebar.getByRole('button', { name: 'Folders', exact: true }).click()
        await expect(search).toHaveCount(0)
        await expect(sidebar.getByRole('button', { name: 'Search conversations: */home.worktrees/*', exact: true })).toBeVisible()
        await sidebar.getByRole('button', { name: 'Clear search', exact: true }).click()
        await expect(sidebar.getByRole('button', { name: 'Search conversations', exact: true })).toBeFocused()
        const folder = list.locator('.hapi-folder').filter({ has: page.locator('header > button[title="Laptop · /workspace/home"]') })
        await expect(folder.locator('.hapi-session-directory')).toHaveText('feature-ui')
        await folder.locator('header .hapi-menu > summary').click()
        await folder.getByRole('button', { name: 'New session here', exact: true }).click()
        const chooser = page.locator('.hapi-dialog').filter({ has: page.locator('.hapi-new-choice') })
        await chooser.getByRole('button', { name: /^Codex/ }).click()
        const creation = page.getByRole('dialog', { name: 'New Codex session', exact: true })
        await expect(creation.getByRole('combobox', { name: 'Machine', exact: true })).toHaveValue('machine-alpha')
        await expect(creation.getByRole('combobox', { name: 'Working directory', exact: true })).toHaveValue('/workspace/home')
        await creation.getByRole('button', { name: 'Cancel', exact: true }).click()

        await sidebar.getByRole('button', { name: 'Recent', exact: true }).click()
        await sidebar.getByRole('button', { name: 'Search conversations', exact: true }).click()
        await sidebar.getByRole('button', { name: 'Date range', exact: true }).click()
        const calendar = sidebar.getByRole('dialog', { name: 'Date range', exact: true })
        await expect(calendar.locator(`[data-date="${dayValue(10)}"]`)).toHaveAttribute('data-activity', 'true')
        await calendar.locator(`[data-date="${dayValue(15)}"]`).click()
        await expect(calendar.getByText('Choose an end date', { exact: true })).toBeVisible()
        await expect(list.locator('[data-recent-total]')).toHaveAttribute('data-recent-total', '6')
        await calendar.locator(`[data-date="${dayValue(10)}"]`).click()
        await expect(calendar).toHaveCount(0)
        await expect(search).toBeFocused()
        await expect(list.locator('[data-recent-total]')).toHaveAttribute('data-recent-total', '3')
        await sidebar.getByRole('button', { name: 'Date range', exact: true }).click()
        await expect(calendar.getByLabel('From date', { exact: true })).toHaveValue(dayValue(10))
        await expect(calendar.getByLabel('Through date', { exact: true })).toHaveValue(dayValue(15))
        await calendar.getByRole('button', { name: 'Clear date range', exact: true }).click()
        await expect(search).toBeFocused()
        await expect(list.locator('[data-recent-total]')).toHaveAttribute('data-recent-total', '6')
        await page.keyboard.press('Escape')
        await expect(calendar).toHaveCount(0)
        await page.screenshot({ path: `${info.outputDir}/original-search-calendar.png`, fullPage: true })
        expect(environment.hapi.spawnRequests).toHaveLength(0)
        expect(environment.hapi.sent).toHaveLength(0)
        expect(errors).toEqual([])
    })

    test('mobile status preferences retain source tasks and pending facts while controlling detailed schedule badges', async ({ page }, info) => {
        const errors: string[] = []
        page.on('pageerror', error => errors.push(error.message))
        const source = environment.hapi.require('native-alpha').session
        environment.hapi.requestApproval(source.id, 'sidebar-approval')
        Object.assign(source, { updatedAt: Date.now() - 3 * 60_000, serviceTier: 'fast', backgroundTaskCount: 4,
            todosUpdatedAt: Date.now(), todos: [{ id: 'done', content: 'Finished', status: 'completed' }, { id: 'todo', content: 'Pending', status: 'pending' }],
            futureScheduledMessageCount: 2, nextScheduledAt: Date.now() + 3600_000 })
        environment.hapi.emit({ type: 'session-updated', sessionId: source.id })
        await page.setViewportSize({ width: 420, height: 900 })
        await page.addInitScript(() => { if (localStorage.getItem('hapi-session-list-status-mode') === null) localStorage.setItem('hapi-session-list-status-mode', 'detailed') })
        await admit(page, environment)
        await page.getByRole('button', { name: 'Open conversation', exact: true }).click()
        const sidebar = page.locator('.hapi-session-picker')
        const row = sidebar.locator('.hapi-session-row').filter({ has: page.locator('.hapi-session-open').filter({ hasText: 'Native Codex alpha' }) })
        await expect(row.locator('.hapi-session-time')).toHaveText(/\dm ago/)
        await expect(row.getByLabel('Tasks: 1/2', { exact: true })).toBeVisible()
        await expect(row.getByLabel('Fast service tier', { exact: true })).toBeVisible()
        await expect(row.getByLabel('1 pending requests', { exact: true })).toBeVisible()
        await expect(row.getByLabel('2 scheduled messages', { exact: true })).toBeVisible()
        await expect(row.getByLabel('4 background tasks', { exact: true })).toBeVisible()
        await sidebar.locator('.hapi-sidebar-options > summary').click()
        const mode = sidebar.getByRole('combobox', { name: 'Mobile row status', exact: true })
        await expect(mode).toHaveValue('detailed')
        await mode.selectOption('standard')
        await expect(row.locator('.hapi-session-scheduled')).toHaveCount(0)
        await expect(row.locator('.hapi-session-background-count')).toHaveCount(0)
        await expect(row.getByLabel('1 pending requests', { exact: true })).toBeVisible()
        await expect(row.getByLabel('Tasks: 1/2', { exact: true })).toBeVisible()
        expect(await page.evaluate(() => localStorage.getItem('hapi-session-list-status-mode'))).toBe('standard')
        await page.screenshot({ path: `${info.outputDir}/original-mobile-row-status.png`, fullPage: true })
        await page.setViewportSize({ width: 1360, height: 900 })
        const desktop = page.locator('.hapi-session-sidebar').locator('.hapi-session-row').filter({ has: page.locator('.hapi-session-open').filter({ hasText: 'Native Codex alpha' }) })
        await expect(desktop.getByLabel('2 scheduled messages', { exact: true })).toBeVisible()
        await page.setViewportSize({ width: 420, height: 900 })
        await page.reload()
        await expect(page.locator('[data-hapi-workspace]')).toBeVisible()
        await page.getByRole('button', { name: 'Open conversation', exact: true }).click()
        await expect(row.locator('.hapi-session-scheduled')).toHaveCount(0)
        await expect(row.getByLabel('Tasks: 1/2', { exact: true })).toBeVisible()
        expect(environment.hapi.approvals).toHaveLength(0)
        expect(environment.hapi.sent).toHaveLength(0)
        expect(errors).toEqual([])
    })
})
