import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { startOfficialEnvironment, type OfficialEnvironment } from './official-runtime.ts';

test.describe('parking the original DSH composer in HAPI notes', () => {
    let environment: OfficialEnvironment;
    test.beforeAll(async () => { environment = await startOfficialEnvironment(); });
    test.afterAll(async () => { await environment?.close(); });
    test('attachments, concurrent edits and an uncertain save survive without sending or duplicating a chat message', async ({ page }) => {
        const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
        await page.goto(environment.launchUrl); await expect(page.locator('[data-hapi-workspace]')).toBeVisible();
        const notice = page.getByRole('dialog', { name: 'Preview Notice', exact: true });
        await notice.waitFor({ state: 'visible', timeout: 2000 }).catch(() => undefined);
        if (await notice.isVisible()) await notice.getByRole('button', { name: 'Continue', exact: true }).click();
        await page.locator('.hapi-session-open').filter({ hasText: 'Native Codex alpha' }).click();
        const pane = page.getByRole('region', { name: 'Pane: Native Codex alpha', exact: true });
        const composer = pane.getByRole('textbox', { name: 'Message or run a task, / commands, @ files or sessions', exact: true });
        const bytes = Buffer.from('Original official composer attachment bytes');
        await composer.fill('A draft parked from the official editor');
        await pane.locator('input[type="file"]').first().setInputFiles({ name: 'parked-source.txt', mimeType: 'text/plain', buffer: bytes });
        await expect(pane.getByRole('group', { name: 'Pending attachments', exact: true })).toContainText('parked-source.txt');
        environment.hapi.extras.dropNextNoteReply = true;
        await pane.getByRole('button', { name: 'Park draft', exact: true }).click();
        const details = pane.getByRole('region', { name: 'Parked composer draft', exact: true });
        await expect(details).toContainText('Saved to scratchlist. The parked draft was cleared.');
        await expect(composer).toHaveText('');
        await expect(pane.getByRole('group', { name: 'Pending attachments', exact: true })).toHaveCount(0);
        expect(environment.hapi.sent).toHaveLength(0); expect(environment.hapi.extras.notes.get('native-alpha')?.size).toBe(1);
        await details.getByRole('button', { name: 'Open scratchlist', exact: true }).click();
        const notes = pane.getByRole('region', { name: 'Scratchlist', exact: true });
        const download = page.waitForEvent('download'); await notes.getByRole('link', { name: 'parked-source.txt', exact: true }).click();
        expect(await readFile((await (await download).path())!)).toEqual(bytes);
        await composer.fill('Captured draft before a slow note reply');
        let finish!: () => void; environment.hapi.extras.nextNoteReply = new Promise(resolve => { finish = resolve; });
        await pane.getByRole('button', { name: 'Park draft', exact: true }).click();
        await expect.poll(() => environment.hapi.extras.notes.get('native-alpha')?.size).toBe(2);
        await composer.fill('Newer edits made while the previous draft is saving'); finish();
        await expect(details).toContainText('The current composer was kept because it changed or was reopened.');
        await expect(composer).toHaveText('Newer edits made while the previous draft is saving');
        environment.hapi.extras.failReadsAfterNextNoteWrite = true;
        await pane.getByRole('button', { name: 'Park draft', exact: true }).click();
        await expect(details.getByRole('alert')).toBeVisible();
        expect(environment.hapi.extras.notes.get('native-alpha')?.size).toBe(3);
        await page.reload(); await expect(pane).toBeVisible();
        await pane.getByRole('button', { name: 'Recover parked draft', exact: true }).click();
        expect(environment.hapi.extras.mutations.filter(row => row.tail === 'scratchlist' && row.method === 'POST')).toHaveLength(3);
        environment.hapi.extras.noteReadsOffline = false;
        await details.getByRole('button', { name: 'Check saved note', exact: true }).click();
        await expect(details).toContainText('Saved to scratchlist.');
        await expect(composer).toHaveText('Newer edits made while the previous draft is saving');
        expect(environment.hapi.extras.mutations.filter(row => row.tail === 'scratchlist' && row.method === 'POST')).toHaveLength(3);
        expect(environment.hapi.extras.mutations.filter(row => row.tail === 'scratchlist/upload')).toHaveLength(1);
        expect(environment.hapi.extras.notes.get('native-beta')?.size ?? 0).toBe(0); expect(environment.hapi.sent).toHaveLength(0);
        expect(errors).toEqual([]); await expect(page.locator('iframe')).toHaveCount(0);
    });
});
